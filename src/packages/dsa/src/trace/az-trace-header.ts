/**
 * `az_trace.h` — the C++ side of the execution tracer, as a string.
 *
 * Injected into the compile-time VFS by the sandbox worker alongside
 * `bits/stdc++.h`. Deliberately NOT folded into that shim: its AST is baked
 * into the 19.5 MB PCH, so adding to it forces a rebuild and redeploy for a
 * header that pulls in nothing the PCH lacks.
 *
 * ## Three decisions that were established by compiling against the real
 * ## toolchain, not by reasoning
 *
 * 1. **ONE entry point with `if constexpr`, never an overload set.** The
 *    natural design — a constrained `v(T)` plus a generic `v(const T&)`
 *    fallback — fails for EVERY type:
 *
 *        error: call to 'v' is ambiguous
 *          note: candidate function [with T = int]   (constrained, by value)
 *          note: candidate function [with T = int]   (fallback, by const&)
 *
 *    `v(T)` and `v(const T&)` are neither more specialized than the other, so
 *    no arrangement of overloads fixes it. `if constexpr` removes overload
 *    resolution from the picture, making ambiguity structurally impossible.
 *
 * 2. **`<cstdio>`, never `<iostream>`.** Touching `std::cerr` here would change
 *    the learner's own stream tie/sync state and could perturb their I/O — and
 *    the one hard requirement is that tracing never changes observable output.
 *
 * 3. **Frames bracketed by `0x01` on BOTH ends, not newline-delimited.** Two
 *    separate failures made this necessary:
 *      - `ConsoleStdout.lineBuffered` silently discards a final unterminated
 *        line, which lost 100% of a first emitter's output;
 *      - the learner's own stderr need not end in a newline, so
 *        `"partial-no-newline \x01{…}\x01more\n"` must split unambiguously.
 *        Odd indices are frames, even indices are their output, rejoined in
 *        order. Newline delimiting would glue their text onto the frame.
 *    Each frame is still followed by `\n` so the interrupted line flushes.
 *
 * 🛑 Caps stop TRACING, never EXECUTION. A capped run must still produce
 * byte-identical stdout, because the same source is judged separately from how
 * it was traced.
 *
 * 🛑 One `write` per record rather than buffering. That costs ~500 tiny
 * syscalls at the default cap — nothing — and buys two things: frames stream to
 * the UI as they are produced, and a program that traps or calls `exit()` still
 * leaves every completed record observable. A buffered version loses the tail
 * exactly when the trace matters most.
 */

export const AZ_TRACE_HEADER = String.raw`#pragma once
// Generated by src/packages/dsa/src/trace/az-trace-header.ts — do not edit.
//
// Execution-trace emitter. Compiles under -std=c++20 -O2 -fno-exceptions and
// declares no global constructors with side effects.

#include <cstdio>
#include <cstring>
#include <type_traits>

// Limits arrive as #defines in the rewritten source, NEVER as -D on the
// command line: the preprocessor state is part of the PCH compatibility hash,
// so a stray -D is the classic "PCH mismatch" trigger.
#ifndef AZ_MAX_STEPS
#define AZ_MAX_STEPS 500
#endif
#ifndef AZ_MAX_LOOP
#define AZ_MAX_LOOP 25
#endif
#ifndef AZ_MAX_DEPTH
#define AZ_MAX_DEPTH 2000
#endif
#ifndef AZ_MAX_ELEMS
#define AZ_MAX_ELEMS 200
#endif
#ifndef AZ_MAX_CHARS
#define AZ_MAX_CHARS 256
#endif
#ifndef AZ_SITES
#define AZ_SITES 1
#endif

namespace __az {

// Frame delimiter. Brackets both ends of a record; see the header comment for
// why this is not a newline.
inline constexpr char SOH = '\x01';

inline long long steps = 0;
inline int depth = 0;
// Global stop: only the STEP and BYTE budgets set this. A per-loop cap must
// NOT, or capping one hot loop would silently end the whole trace and nothing
// after it would ever be seen — which defeats the point of per-site counters.
inline bool dead = false;
// One cap record per reason, so a diagnosis is never swallowed by an earlier
// unrelated cap.
inline bool cap_said[4] = {false, false, false, false};
inline bool open_rec = false;
inline bool first_var = false;
inline int nest = 0;
inline int loop_hits[AZ_SITES + 1] = {0};

// ---------------------------------------------------------------- raw output

inline void put(char c) { fputc(c, stderr); }

inline void ps(const char* s) { fputs(s, stderr); }

inline void put_i(long long v) {
    char b[24];
    // snprintf rather than hand-rolled digits: correct for LLONG_MIN, where
    // negating the magnitude would overflow.
    int n = snprintf(b, sizeof b, "%lld", v);
    if (n > 0) fwrite(b, 1, (size_t)n, stderr);
}

inline void put_u(unsigned long long v) {
    char b[24];
    int n = snprintf(b, sizeof b, "%llu", v);
    if (n > 0) fwrite(b, 1, (size_t)n, stderr);
}

inline void put_d(double v) {
    // JSON has no NaN or Infinity, so they become quoted strings rather than a
    // document the parser would reject.
    if (!(v == v)) { ps("\"NaN\""); return; }
    if (v > 1.797e308) { ps("\"Infinity\""); return; }
    if (v < -1.797e308) { ps("\"-Infinity\""); return; }
    char b[40];
    int n = snprintf(b, sizeof b, "%.10g", v);
    if (n > 0) fwrite(b, 1, (size_t)n, stderr);
    else ps("null");
}

inline void sesc(const char* p, size_t n) {
    if (n > (size_t)AZ_MAX_CHARS) n = (size_t)AZ_MAX_CHARS;
    for (size_t i = 0; i < n; ++i) {
        char c = p[i];
        if (c == '"' || c == '\\') { put('\\'); put(c); }
        else if ((unsigned char)c < 0x20) {
            // Escaping every byte below 0x20 is what keeps 0x01 safe as a
            // frame delimiter: a record can never contain a literal one.
            char b[8];
            snprintf(b, sizeof b, "\\u%04x", (unsigned)(unsigned char)c);
            ps(b);
        } else put(c);
    }
}

inline void q(const char* p, size_t n) { put('"'); sesc(p, n); put('"'); }

// ------------------------------------------------------------ value emitting

template <class T> struct is_pair_ : std::false_type {};
template <class A, class B> struct is_pair_<std::pair<A, B>> : std::true_type {};

template <class T>
concept Iterable_ = requires(const T& c) { c.begin(); c.end(); };

/**
 * THE single entry point. An if constexpr chain, deliberately — see the header
 * comment on why an overload set cannot work here.
 */
template <class T>
void v(const T& x) {
    using U = std::remove_cv_t<std::remove_reference_t<T>>;

    if constexpr (std::is_same_v<U, bool>) {
        ps(x ? "true" : "false");
    } else if constexpr (std::is_same_v<U, char>) {
        q(reinterpret_cast<const char*>(&x), 1);
    } else if constexpr (std::is_same_v<U, signed char> || std::is_same_v<U, unsigned char>) {
        put_i((long long)x);
    } else if constexpr (std::is_integral_v<U>) {
        if constexpr (std::is_signed_v<U>) put_i((long long)x);
        else put_u((unsigned long long)x);
    } else if constexpr (std::is_floating_point_v<U>) {
        put_d((double)x);
    } else if constexpr (std::is_same_v<U, const char*> || std::is_same_v<U, char*>) {
        if (x == nullptr) ps("null");
        else q(x, strlen(x));
    } else if constexpr (std::is_array_v<U>) {
        // A raw array decays and carries no size, so there is nothing truthful
        // to print. Say so rather than guessing a length.
        ps("\"<array>\"");
    } else if constexpr (std::is_pointer_v<U>) {
        if (x == nullptr) ps("null");
        else ps("\"<ptr>\"");
    } else if constexpr (requires { x.c_str(); x.size(); }) {
        // std::string / string_view, matched by shape so this header needs no
        // <string> include of its own.
        q(x.c_str(), x.size());
    } else if constexpr (requires {
                             x.size();
                             // NESTED requires, not a top-level &&. An
                             // if-constexpr condition does NOT short-circuit at
                             // the type level: both operands get instantiated,
                             // so dereferencing x.data() on a map, set or pair
                             // is a hard error rather than a failed constraint.
                             // Inside the requires-clause it is an unevaluated
                             // context and simply does not match.
                             requires std::is_same_v<
                                 std::remove_cv_t<std::remove_reference_t<decltype(*x.data())>>,
                                 char>;
                         }) {
        // string_view and friends. The element type must be constrained to
        // char: a bare data()/size() requirement also matches vector<int> and
        // array<int,N>, which then take the string path and fail with
        // "no known conversion from 'const int *' to 'const char *'".
        q(x.data(), x.size());
    } else if constexpr (is_pair_<U>::value) {
        put('[');
        v(x.first);
        put(',');
        v(x.second);
        put(']');
    } else if constexpr (Iterable_<U>) {
        if (nest >= 3) { ps("\"<deep>\""); return; }
        ++nest;
        put('[');
        size_t i = 0;
        for (auto it = x.begin(); it != x.end(); ++it) {
            if (i >= (size_t)AZ_MAX_ELEMS) {
                // Report the elision rather than showing a prefix as the whole.
                if (i) put(',');
                ps("\"\\u2026\"");
                break;
            }
            if (i) put(',');
            v(*it);
            ++i;
        }
        put(']');
        --nest;
    } else if constexpr (std::is_enum_v<U>) {
        put_i((long long)x);
    } else {
        // A user struct with no printable shape. Honest placeholder beats a
        // compile error, which is the whole point of if constexpr here.
        ps("\"<?>\"");
    }
}

// ------------------------------------------------------------------- records

inline int cap_slot(const char* reason) {
    if (reason[0] == 's') return 0;  // steps
    if (reason[0] == 'l') return 1;  // loop
    if (reason[0] == 'd') return 2;  // depth
    return 3;                         // bytes
}

/**
 * Report a cap. Deduped per REASON rather than globally: a depth diagnosis is
 * worth emitting even after the step budget is spent, because "recursion
 * reached depth N" is the actionable part.
 */
inline void emit_cap(const char* reason, int line) {
    const int slot = cap_slot(reason);
    if (cap_said[slot]) return;
    cap_said[slot] = true;
    put(SOH);
    ps("{\"k\":\"cap\",\"reason\":\"");
    ps(reason);
    ps("\",\"l\":");
    put_i(line);
    put('}');
    put(SOH);
    put('\n');
    fflush(stderr);
}

// Count one iteration of the loop identified by 'site'. Never blocks
// execution: a cap stops tracing, not the program.
//
// NOTE to future editors: no backticks anywhere inside this C++ string. It is
// a String.raw template literal, so one backtick terminates it and the rest of
// the header is parsed as TypeScript. There is a test that enforces this.
inline void tick(int site) {
    if (site > 0 && site <= AZ_SITES) ++loop_hits[site];
}

/** True if a record should be emitted here. Opens it. */
inline bool on(int line, int site) {
    if (dead) return false;
    if (steps >= (long long)AZ_MAX_STEPS) {
        // Global: the budget really is spent.
        emit_cap("steps", line);
        dead = true;
        return false;
    }
    if (site > 0 && site <= AZ_SITES && loop_hits[site] > AZ_MAX_LOOP) {
        // Per-site ONLY. Tracing continues elsewhere, which is the entire
        // reason loop_hits is indexed by site.
        emit_cap("loop", line);
        return false;
    }
    ++steps;
    open_rec = true;
    first_var = true;
    put(SOH);
    ps("{\"k\":\"f\",\"s\":");
    put_i(steps);
    ps(",\"l\":");
    put_i(line);
    ps(",\"d\":");
    put_i(depth);
    ps(",\"v\":{");
    return true;
}

/** Name a variable. Stringification lives here, so a mismatch is impossible. */
inline void n(const char* name, bool first) {
    if (!open_rec) return;
    if (!first) put(',');
    q(name, strlen(name));
    put(':');
}

inline void end() {
    if (!open_rec) return;
    open_rec = false;
    ps("}}");
    put(SOH);
    put('\n');
    // Flushed per record: a trap or exit() must still leave completed frames
    // observable, and the UI streams them.
    fflush(stderr);
}

/**
 * Recursion-depth guard, one per instrumented function body.
 *
 * Trips BEFORE the real stack dies, so the learner gets "recursion reached
 * depth N" instead of an opaque wasm trap. The destructor runs on every exit
 * path, which is why this is a guard object rather than a pair of calls.
 */
struct Depth {
    explicit Depth(int line) {
        ++depth;
        if (depth > AZ_MAX_DEPTH) emit_cap("depth", line);
    }
    ~Depth() { --depth; }
    Depth(const Depth&) = delete;
    Depth& operator=(const Depth&) = delete;
};

}  // namespace __az

// Stringification in OUR header keeps the learner's source macro-free and makes
// a name/expression mismatch impossible by construction.
#define AZ_V(first, x) __az::n(#x, first); __az::v(x)
`;

/** Caps baked into the rewritten source as #defines. */
export interface AzLimits {
  maxSteps: number;
  maxLoopIterations: number;
  maxDepth: number;
  maxElements: number;
  maxChars: number;
}

export const AZ_DEFAULTS: AzLimits = {
  maxSteps: 500,
  maxLoopIterations: 25,
  maxDepth: 2000,
  maxElements: 200,
  maxChars: 256,
};

/**
 * Hard ceilings. The run is synchronous and uninterruptible, so an unbounded
 * trace hangs the worker until the 30 s watchdog — the cap is what makes
 * stepping cheap enough to explore freely.
 */
export const AZ_CEILINGS: AzLimits = {
  maxSteps: 5000,
  maxLoopIterations: 200,
  maxDepth: 10_000,
  maxElements: 2000,
  maxChars: 4096,
};

export function clampLimits(requested?: Partial<AzLimits>): AzLimits {
  const pick = (key: keyof AzLimits): number => {
    const value = requested?.[key];
    if (typeof value !== "number" || !Number.isFinite(value) || value < 1) return AZ_DEFAULTS[key];
    return Math.min(Math.floor(value), AZ_CEILINGS[key]);
  };
  return {
    maxSteps: pick("maxSteps"),
    maxLoopIterations: pick("maxLoopIterations"),
    maxDepth: pick("maxDepth"),
    maxElements: pick("maxElements"),
    maxChars: pick("maxChars"),
  };
}

/** The `#define` block prepended to the rewritten translation unit. */
export function limitsPrelude(limits: AzLimits, sites: number): string {
  return [
    `#define AZ_MAX_STEPS ${limits.maxSteps}`,
    `#define AZ_MAX_LOOP ${limits.maxLoopIterations}`,
    `#define AZ_MAX_DEPTH ${limits.maxDepth}`,
    `#define AZ_MAX_ELEMS ${limits.maxElements}`,
    `#define AZ_MAX_CHARS ${limits.maxChars}`,
    `#define AZ_SITES ${Math.max(1, sites)}`,
    `#include "az_trace.h"`,
    // Realigns the compiler's own line numbering so diagnostics stay readable
    // while developing this. Emitted line numbers come from the ORIGINAL
    // source regardless, so correctness does not depend on it.
    `#line 1`,
    "",
  ].join("\n");
}
